--#BEGIN_OBJECT:FUNCTION
CREATE OR REPLACE EDITIONABLE FUNCTION "WKSP_PAAS"."GET_EMP1_NAME" 
(
    P_EMPNO IN NUMBER
)
RETURN VARCHAR2
AS
    V_ENAME VARCHAR2(10);
BEGIN

    SELECT ENAME
    INTO V_ENAME
    FROM EMP1
    WHERE EMPNO = P_EMPNO;

    RETURN V_ENAME;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'EMPLOYEE NOT FOUND';

END GET_EMP1_NAME;
/
/
--#END_OBJECT


EXIT SUCCESS
